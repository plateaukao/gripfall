const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { mkdtempSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const output = mkdtempSync(join(tmpdir(), 'gripfall-3d-')); 
  const browser = await chromium.launch({ channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, hasTouch: true });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error' || (m.type() === 'warning' && m.text().includes('BufferGeometry'))) errors.push(m.text()); });
  await page.clock.install();
  await page.route(/https:\/\/[^/]*google-analytics\.com\/g\/collect/, route => route.fulfill({ status: 204 }));
  await page.goto(process.env.GRIPFALL_URL || pathToFileURL(join(__dirname, 'index.html')).href);
  await page.clock.runFor(50);
  assert.equal(await page.locator('#scene').getAttribute('data-ready'), 'true');
  assert.equal(await page.locator('#renderError').isVisible(), false);
  await page.screenshot({ path: join(output, 'initial.png') });
  const original = await page.evaluate(() => gripfall.getView());
  await page.mouse.move(800, 400); await page.mouse.down();
  await page.mouse.move(1050, 470, { steps: 15 }); await page.mouse.up();
  await page.clock.runFor(1000);
  const rotated = await page.evaluate(() => gripfall.getView());
  assert.notDeepEqual(rotated.position, original.position, 'Drag must orbit');
  assert.deepEqual(rotated.target, original.target, 'Orbit keeps its target');
  await page.screenshot({ path: join(output, 'orbit.png') });
  await page.mouse.wheel(0, -320); await page.clock.runFor(1000);
  assert((await page.evaluate(() => gripfall.getView())).distance < rotated.distance, 'Wheel must zoom in');
  await page.mouse.move(800, 400); await page.mouse.down({ button: 'right' });
  await page.mouse.move(930, 430, { steps: 10 }); await page.mouse.up({ button: 'right' });
  await page.clock.runFor(1000);
  assert.notDeepEqual((await page.evaluate(() => gripfall.getView())).target, rotated.target, 'Right-drag must pan');
  await page.locator('#resetView').click(); await page.clock.runFor(1000);
  const reset = await page.evaluate(() => gripfall.getView());
  reset.position.forEach((n, i) => assert(Math.abs(n - original.position[i]) < .0001));
  await page.locator('#scene').focus();
  await page.keyboard.down('ArrowUp'); await page.clock.runFor(500);
  let state = await page.evaluate(() => gripfall.getState());
  assert(state.vacuum > .99 && state.state === 'ready');
  assert.deepEqual(await page.evaluate(() => gripfall.getView()), reset, 'Arrow keys must not move the camera');
  assert.equal(await page.locator('[data-hold=vacuum]').getAttribute('aria-pressed'), 'true');
  await page.keyboard.down('Space'); await page.clock.runFor(500);
  state = await page.evaluate(() => gripfall.getState()); assert(state.x > 100);
  await page.keyboard.up('Space'); await page.keyboard.up('ArrowUp');
  await page.evaluate(() => gripfall.startDemo()); await page.clock.runFor(7000);
  await page.screenshot({ path: join(output, 'flight.png') });
  await page.clock.runFor(10000);
  state = await page.evaluate(() => gripfall.getState());
  assert.equal(state.state, 'landed'); assert(state.releaseVX < 0);
  assert.equal(await page.locator('[data-hold].active').count(), 0);
  await page.screenshot({ path: join(output, 'landing.png') });
  await page.locator('#retry').click();
  await page.setViewportSize({ width: 390, height: 844 }); await page.clock.runFor(300);
  await page.screenshot({ path: join(output, 'mobile.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  const beforeTouch = await page.evaluate(() => gripfall.getView());
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 140, y: 330, id: 1 }] });
  for (let x = 145; x <= 220; x += 5)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: 350, id: 1 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.clock.runFor(500);
  const afterTouch = await page.evaluate(() => gripfall.getView());
  assert(Math.abs((afterTouch.position[0] - afterTouch.target[0]) - (beforeTouch.position[0] - beforeTouch.target[0])) > 1, 'One-finger touch must orbit');
  await page.locator('#resetView').click();
  // Two touch controls can apply drive and suction simultaneously.
  const drive = await page.locator('[data-hold=drive]').boundingBox();
  const vacuum = await page.locator('[data-hold=vacuum]').boundingBox();
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [
    { x: drive.x + drive.width / 2, y: drive.y + drive.height / 2, id: 1 },
    { x: vacuum.x + vacuum.width / 2, y: vacuum.y + vacuum.height / 2, id: 2 }
  ] });
  await page.clock.runFor(500);
  const touchState = await page.evaluate(() => gripfall.getState());
  assert(touchState.x > 100 && touchState.vacuum > .99, 'Touch buttons must keep drive and vacuum independent');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.evaluate(() => gripfall.startDemo()); await page.clock.runFor(17000);
  assert.equal((await page.evaluate(() => gripfall.getState())).state, 'landed');
  assert.deepEqual(errors, []);
  console.log('PASS: WebGL scene, orbit, zoom, pan, reset view, keyboard isolation, highlighted inputs, successful demo, mobile layout and demo.');
  console.log('Screenshots:', output);
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
